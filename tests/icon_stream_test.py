"""Check exported icon streams against separately rasterized inputs on this host."""
import argparse
import json
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import gen_aa_icons as icons  # noqa: E402
from ui_font_data import huff_pack, huff_unpack  # noqa: E402


def arrays(source):
    result = {}
    for m in re.finditer(r"static const (uint8_t|uint16_t|uint32_t) (AI\w+)\[[^]]*\]\s*=\s*\{(.*?)\};",
                         source, re.S):
        result[m[2]] = [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", m[3])]
    return result


def reference(directory):
    """Raw raster input, independent of the candidate's stream packing and offsets."""
    font = ROOT / "web/fukiai.ttf"
    cps = icons.glyph_table(font)
    legacy = json.loads((ROOT / "assets/icons.json").read_text())["names"]
    names = legacy + list(icons.EXTRA)
    glyphs = {n: icons.resolve(g, cps) for n, g in {**icons.LEGACY, **icons.EXTRA}.items()}
    fitted, fixed = icons.fitted_font(font, directory, set(glyphs.values()))
    mended = {g for g, _ in fixed}
    cells = {}
    for size in (12, 16, 24):
        subset = ([n for n in names if (n in legacy and n not in icons.NOT_DRAWN) or n in icons.SMALL_EXTRA]
                  if size == 12 else [n for n in names if n in
                                       (icons.HUGE_DEFAULT if size == 24 else icons.BIG_DEFAULT)])
        cells[size] = []
        for name in subset:
            raw, ink = icons.ar.raster_icon(fitted if glyphs[name] in mended else str(font),
                                           size, cps[glyphs[name]], 1.0)
            if not ink:
                raise AssertionError(f"empty source icon: {name} at {size}")
            values = [(raw[i // 2] >> (0 if i & 1 else 4)) & 15 for i in range(size * size)]
            cells[size].append((name, bytes(raw), values))
    return names, cells


def c_reference(path, cells):
    lines = ["/* Host-only raw input oracle, Fukiai MIT; generated by tests/icon_stream_test.py. */"]
    entries = []
    for size, group in cells.items():
        for index, (_, raw, _) in enumerate(group):
            name = f"icon_raw_{size}_{index}"
            lines.append(f"static const uint8_t {name}[] = {{{','.join(map(str, raw))}}};")
            entries.append(f"{{{size}, AI{size}_DATA + AI{size}_OFF[{index}], {name}}}")
    lines.append("static const struct { uint32_t size; const uint8_t *packed, *raw; } icon_cases[] = {"
                 + ",".join(entries) + "};")
    Path(path).write_text("\n".join(lines) + "\n")


class IconStreams(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temporary = tempfile.TemporaryDirectory(prefix="icons-", dir=ROOT / "build")
        cls.addClassCleanup(cls.temporary.cleanup)
        cls.directory = Path(cls.temporary.name)
        cls.names, cls.cells = reference(cls.directory)
        cls.outputs = []
        for name in ("first.h", "second.h"):
            target = cls.directory / name
            subprocess.run([sys.executable, str(ROOT / "tools/gen_aa_icons.py"), str(target)],
                           cwd=ROOT, check=True, capture_output=True, text=True)
            cls.outputs.append(target.read_text())
        cls.export = arrays(cls.outputs[0])

    def test_actual_export_metadata_and_pixels(self):
        header = (ROOT / "build/gen/ui_icons.h").read_text()
        self.assertEqual(header, self.outputs[0], "build/gen/ui_icons.h must be regenerated")
        self.assertEqual(self.outputs[0], self.outputs[1], "nondeterministic output")
        ids = re.findall(r"^\s+ICON_(\w+),", header, re.M)
        self.assertEqual(ids, [name.upper() for name in self.names])
        values = [v for group in self.cells.values() for _, _, v in group]
        book, packed = huff_pack(values)  # all unchanged cells, including duplicates
        self.assertEqual(self.export["AI_HC"], book, "dedup must not alter frequency/codebook")
        streams = iter(packed)
        for size, group in self.cells.items():
            data = bytes(self.export[f"AI{size}_DATA"])
            offsets = self.export[f"AI{size}_OFF"]
            self.assertEqual(len(offsets), len(group))
            self.assertIn(f"#define AI{size}_N {len(group)}\n", header)
            self.assertLess(len(data), 65536)
            self.assertEqual(data[-2:], bytes(2))
            index, inks, plain, first = [255] * len(self.names), [], bytearray(), {}
            for cell, (name, raw, expected) in enumerate(group):
                stream = next(streams)
                off = offsets[cell]
                expected_off = first.get(stream, len(plain)) if size == 12 else len(plain)
                self.assertEqual(off, expected_off, (size, cell, "stable first occurrence"))
                if size != 12 or stream not in first:
                    first[stream] = len(plain)
                    plain.extend(stream)
                self.assertEqual(data[off:off + len(stream)], stream)
                self.assertGreaterEqual(len(data) - off - len(stream), 2)
                self.assertEqual(huff_unpack(book, data[off:], size * size), expected)
                index[self.names.index(name)] = cell
                points = [(i % size, i // size) for i, v in enumerate(expected) if v]
                x0, y0 = min(x for x, _ in points), min(y for _, y in points)
                x1, y1 = max(x for x, _ in points) + 1, max(y for _, y in points) + 1
                inks.append(x0 | y0 << 4 | (x1 - 1) << 8 | (y1 - 1) << 12 if size <= 16 else
                            x0 | y0 << 8 | x1 << 16 | y1 << 24)
            self.assertEqual(data, plain + bytes(2))
            self.assertEqual(self.export[f"AI{size}_IDX"], index)
            self.assertEqual(self.export[f"AI{size}_INK"], inks)

    def test_complete_stream_identity_and_padding(self):
        streams = [b"\x80", b"\x80\x00", b"\x80", b"", b"\x80\x00", b""]
        data, offsets = icons.cell_streams(streams, True)
        self.assertEqual(offsets, [0, 1, 0, 3, 1, 3])
        self.assertEqual(data, b"\x80\x80\x00\x00\x00")
        self.assertEqual(icons.cell_streams([], True), (bytearray(2), []))
        self.assertEqual(icons.cell_streams([b"x", b"x"]), (bytearray(b"xx\0\0"), [0, 1]))
        # Independent calls represent different sizes/books: there is no shared dictionary.
        self.assertEqual(icons.cell_streams([b"x"], True)[1], [0])

    def test_odd_empty_and_codebook_boundaries(self):
        # A canonical prefix chain exercises both sides of the C LUT's 8-bit boundary and length 15.
        book = [1] * 14 + [2] + list(range(16))
        streams = [b"\x00", b"\xfe", b"\xff\x00", b"\xff\xfc", b"\xff\xfe", b""]
        expected = [[0], [7], [8], [14], [15], []]
        data, offsets = icons.cell_streams(streams + streams, True)
        self.assertEqual(offsets[:6], offsets[6:])
        for off, values in zip(offsets, expected * 2):
            self.assertEqual(huff_unpack(book, data[off:], len(values)), values)
        for values in ([1, 2, 3], [0] * 17, [15] * 33):
            hc, encoded = huff_pack([values, values])
            blob, offs = icons.cell_streams(encoded, True)
            self.assertEqual(offs, [0, 0])
            self.assertEqual(huff_unpack(hc, blob, len(values)), values)

    def test_offset_limit_includes_final_lookahead(self):
        data, offsets = icons.cell_streams([b"a" * 65532, b"b"], True)
        self.assertEqual((len(data), offsets), (65535, [0, 65532]))
        self.assertEqual(icons.cell_streams([b"a" * 65533] * 2, True)[1], [0, 0])
        for streams in ([b"a" * 65534], [b"a" * 65533, b"b"]):
            with self.assertRaisesRegex(ValueError, "64 KiB"):
                icons.cell_streams(streams, True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--c-reference", type=Path, required=True)
    args = parser.parse_args()
    suite = unittest.defaultTestLoader.loadTestsFromTestCase(IconStreams)
    result = unittest.TextTestRunner(verbosity=2).run(suite)
    if not result.wasSuccessful():
        raise SystemExit(1)
    # Re-rasterize the input for the C oracle; never derive expected pixels from the candidate export.
    with tempfile.TemporaryDirectory(prefix="icon-reference-", dir=ROOT / "build") as directory:
        _, cells = reference(directory)
        c_reference(args.c_reference, cells)
    print("Icons: exported metadata/book/pixels deterministic; full-stream reuse, odd/empty/long-code/padding/offset fixtures")
