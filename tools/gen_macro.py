"""Emit only the Braids tables used by MACRO, from the attributed local asset."""
import json
from pathlib import Path
import sys


def generate(dst):
    asset = Path(__file__).resolve().parent.parent / "assets/braids/macro.json"
    data = json.loads(asset.read_text())
    waves = data["waves"]
    if len(waves) != 64 or any(len(w) != 129 or any(not 0 <= v <= 255 for v in w) for w in waves):
        raise ValueError("MACRO needs Braids' 64 WAV LINE waves, each 128 samples plus its wrap point")
    lines = ["/* SPDX-License-Identifier: MIT",
             " * Copyright 2012 Emilie Gillet. See LICENSES/MIT-Braids.txt.",
             " * Generated by tools/gen_macro.py from assets/braids/macro.json.",
             f" * eurorack revision {data['upstream_revision']} */",
             "static const uint8_t MACRO_WAVES[65][129] = {"]
    # Clamp the last scan segment to its endpoint instead of reading beyond wave_line.
    lines.extend("    {" + ",".join(map(str, w)) + "}," for w in [*waves, waves[-1]])
    lines.append("};")
    for key in ("sine", "sine_fold", "triangle_fold"):
        values = data[key]
        if len(values) != 257 or any(not -32768 <= v <= 32767 for v in values):
            raise ValueError(f"invalid Braids {key} table")
        lines.append(f"static const int16_t MACRO_{key.upper()}[257] = {{")
        lines.extend("    " + ",".join(map(str, values[i:i + 16])) + "," for i in range(0, 257, 16))
        lines.append("};")
    Path(dst).write_text("\n".join(lines) + "\n")
    print("MACRO: 64 scanning waves + endpoint guard, sine and two folders; 9927 B of immutable tables")


if __name__ == "__main__":
    generate(sys.argv[1])
